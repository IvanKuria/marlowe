def main():
    if len(sys.argv) == 2 and sys.argv[1] in SCENES:
        scene, composition = SCENES[sys.argv[1]]
    elif len(sys.argv) == 3:
        scene, composition = sys.argv[1], sys.argv[2]
    else:
        print(__doc__)
        print("known scenes:", ", ".join(SCENES))
        sys.exit(1)

    print("model:     ", MODEL)
    print("aspect:    ", ASPECT)
    print("references:", REFERENCES)
    print()
